"""给不写代码的人看的那一层：报告里的每一栏、每一种结论、每一个检测器在说什么。

## 为什么这一层要单独存在，而不是把话说进模板里

2026-10-03，这份东西的第一个真实用户——一个不写代码、也不打算写代码的人——用
了十分钟之后说：「我其实有点不会用，也看不懂」。他点开一份运行报告，看到的是
一张写着 `loop.cross_session` / `inconclusive` / `未覆盖` 的表。每一个字他都认得，
连起来他不知道该不该担心。

那不是一个可以靠「写得再清楚一点」解决的排版问题。报告现在的每一句话都是写给
**知道这套系统怎么工作的人**的：`未覆盖` 是一个精确的词，它在这个项目里有严格
定义（场景没对这条结论写预期，计入覆盖率但不让运行失败）——**而一个不知道检测器
是什么的人，读不出这个词背后的那整套约定**。

所以这一层是**翻译**，不是简化：底下那套判据一个字都不动，只是在它旁边补一句
「这一栏在说什么、正常该长什么样、你现在这样意味着什么」。

## 三条纪律

**一、不许把判不了说成没问题。** 这是整个项目最在意的一件事（见
`docs/detectors.md` 的四态语义），而通俗化极易把它丢掉：`inconclusive` 说成
「暂时没发现问题」读者会读成「没问题」。所以三种结论的解释里，
`inconclusive` 那条必须自己说出「判不了」三个字，并且**不许**出现「没问题」。
`tests/test_explain_coverage.py` 里有一条专门盯这个的断言——它不是修辞检查，
它守的是这个产品唯一值钱的地方。

**二、通俗话不许说出比观测更多的话。** 翻译可以换词，不能加戏。比如
`loop.cross_session` 的判据是「两次运行里出现了同一组调用」，那就只能说到这个
程度，不能写成「它在上次的经验里迷路了」。这条没有机械闸门（判断"有没有加戏"
本身就需要读得懂），但它是这一层唯一的硬边界，改这些字的人要自己守住。

**三、每一条解释都挂在代码里真实存在的名字上。** 检测器名字取自
`KNOWN_DETECTORS` 与边界那四个，理由码取自源码里真的会写进
`detail["reason_code"]` 的常量——两边都由 `tests/test_explain_coverage.py`
现算，不是抄的。**这里多出一条、源码里少一条，闸门会红**：一张会腐烂的
翻译表比没有翻译表更坏，因为它会把「这个名字现在不存在了」显示成
「这一项没有解释」，而读的人以为自己看到的是全部。
"""

